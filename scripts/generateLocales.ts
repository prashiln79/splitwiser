const outputDir = path.resolve(__dirname, '../src/i18n/locales');

for (const locale of LOCALES) {
  const dir = path.join(outputDir, locale);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  const localeData = ALL_DATA[locale];
  for (const [namespace, content] of Object.entries(localeData)) {
    const filePath = path.join(dir, `${namespace}.json`);
    fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf8');
  }
}

